"""
Visualization-ready output schema (Phase 7).

This is metadata for a chart, not a rendered chart -- no chart library
runs anywhere in this project yet (that's a later phase's job). Kept in
its own file per the project's structure diagram: it's a distinct
concern from dataset/analysis schemas, and other modules only need to
import ChartData without pulling in the rest of schemas/analysis.py.
"""

from typing import Any, Literal

from pydantic import BaseModel, Field

ChartType = Literal["bar", "line", "pie", "table", "scatter"]


class ChartData(BaseModel):
    """Structured chart description, built deterministically from real query results.

    Nothing about `data` is ever generated by an LLM -- see
    agent/nodes.py::build_chart_data_node, which populates this directly
    from an already-executed query's actual rows. The model's only
    influence is choosing `chart_type` (or None for "no chart needed"),
    via QuestionAnalysis.suggested_chart_type.
    """

    chart_type: ChartType
    title: str
    x_axis: str | None = Field(default=None, description="Column name used for the X axis / categories")
    y_axis: str | None = Field(default=None, description="Column name used for the Y axis / values")
    data: list[dict[str, Any]] = Field(description="The actual rows backing this chart, taken directly from a query result")
