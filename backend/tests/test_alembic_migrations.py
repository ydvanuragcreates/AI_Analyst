"""
Runs the REAL Alembic migration chain (not `Base.metadata.create_all`,
which every other test's `sqlite_db` fixture uses) against a throwaway
SQLite file -- proving `alembic upgrade head` and `alembic downgrade`
actually execute cleanly through every migration, in order, including
the SQLite-specific `batch_alter_table` adjustment the second migration
needed (see alembic/versions/e03732e04887_*.py's docstring) after the
raw autogenerated `create_unique_constraint` failed outright on SQLite.

This is a SQLite compatibility test, not a PostgreSQL integration test --
see tests/test_postgres_integration.py (skipped unless a real PostgreSQL
is available) for the distinction the Phase 9 audit explicitly asked for.
"""

import os
import uuid

from alembic import command
from alembic.config import Config


def _alembic_config(sqlite_url: str) -> Config:
    backend_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    config = Config(os.path.join(backend_dir, "alembic.ini"))
    config.set_main_option("sqlalchemy.url", sqlite_url)
    return config


def test_upgrade_head_then_downgrade_to_base_runs_cleanly(tmp_path) -> None:
    db_path = tmp_path / f"alembic_test_{uuid.uuid4().hex}.db"
    config = _alembic_config(f"sqlite+aiosqlite:///{db_path}")

    command.upgrade(config, "head")

    import sqlite3

    conn = sqlite3.connect(str(db_path))
    try:
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        assert {"users", "datasets", "analyses", "analysis_jobs", "analysis_messages", "deep_analysis_results"} <= tables

        analyses_sql = conn.execute(
            "SELECT sql FROM sqlite_master WHERE name = 'analyses'"
        ).fetchone()[0]
        assert "uq_analyses_user_id_idempotency_key" in analyses_sql
        assert "mode" in analyses_sql
    finally:
        conn.close()

    # Full downgrade chain, one step at a time, same as a real operator
    # rolling back a bad deploy would run it. Three migrations now (Phase
    # 10 added a third -- see alembic/versions/c391ffe21c7a_*.py), so
    # three single-step downgrades to reach base.
    command.downgrade(config, "-1")
    command.downgrade(config, "-1")
    command.downgrade(config, "-1")

    conn = sqlite3.connect(str(db_path))
    try:
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        assert "analyses" not in tables
        assert "deep_analysis_results" not in tables
    finally:
        conn.close()

    # And back up again -- the round trip must be repeatable, not just
    # "upgrade once and never look back."
    command.upgrade(config, "head")
    conn = sqlite3.connect(str(db_path))
    try:
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        assert "analyses" in tables
    finally:
        conn.close()


def test_idempotency_unique_constraint_rejects_duplicate_user_and_key(tmp_path) -> None:
    """The DB-level enforcement, not just the application-level
    check-then-insert (see api/routes/analysis_jobs.py) -- proves the
    constraint alembic just created actually does something."""

    import sqlite3

    db_path = tmp_path / f"alembic_test_{uuid.uuid4().hex}.db"
    config = _alembic_config(f"sqlite+aiosqlite:///{db_path}")
    command.upgrade(config, "head")

    conn = sqlite3.connect(str(db_path))
    try:
        user_id = uuid.uuid4().hex
        dataset_id = uuid.uuid4().hex
        conn.execute(
            "INSERT INTO users (id, email, password_hash, created_at, updated_at) VALUES (?, ?, 'x', datetime('now'), datetime('now'))",
            (user_id, f"{user_id}@example.com"),
        )
        conn.execute(
            "INSERT INTO datasets (id, user_id, name, file_name, file_type, file_size, version, file_hash, created_at, updated_at) "
            "VALUES (?, ?, 'n', 'n.csv', 'csv', 1, 1, 'h', datetime('now'), datetime('now'))",
            (dataset_id, user_id),
        )
        common_args = (user_id, dataset_id, 1, "t1", "q", "queued", "same-key")
        conn.execute(
            "INSERT INTO analyses (id, user_id, dataset_id, dataset_version, thread_id, question, status, idempotency_key, created_at, updated_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))",
            (uuid.uuid4().hex, *common_args),
        )
        conn.commit()

        try:
            conn.execute(
                "INSERT INTO analyses (id, user_id, dataset_id, dataset_version, thread_id, question, status, idempotency_key, created_at, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))",
                (uuid.uuid4().hex, *common_args),
            )
            conn.commit()
            raised = False
        except sqlite3.IntegrityError:
            raised = True

        assert raised, "duplicate (user_id, idempotency_key) should have violated the unique constraint"
    finally:
        conn.close()
